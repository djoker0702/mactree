"""Detect residual developer artifacts (caches, dependency dirs, build output).

These are directories that are safe-ish to delete because they can be
regenerated by the relevant tool (``npm install``, ``terraform init``,
``cargo build`` …). We walk the already-scanned :class:`~mactree.scanner.Node`
tree — no extra disk I/O — and match directory names against a known set.

When a directory matches, we record it as a single finding and do **not**
descend into it (so ``node_modules`` is one entry, not 20 000).
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, List

from .scanner import Node


# name -> short human description of why it's residual / how to regenerate it
KNOWN_ARTIFACTS: Dict[str, str] = {
    # JavaScript / Node
    "node_modules": "npm/yarn deps — regenerate with install",
    ".npm": "npm cache",
    ".yarn": "yarn cache/state",
    ".pnpm-store": "pnpm content-addressable store",
    "bower_components": "bower deps (legacy)",
    ".next": "Next.js build output",
    ".nuxt": "Nuxt build output",
    ".svelte-kit": "SvelteKit build output",
    ".parcel-cache": "Parcel bundler cache",
    ".turbo": "Turborepo cache",
    # Python
    "__pycache__": "Python bytecode cache",
    ".pytest_cache": "pytest cache",
    ".mypy_cache": "mypy cache",
    ".ruff_cache": "ruff cache",
    ".tox": "tox environments",
    ".venv": "Python virtualenv",
    "venv": "Python virtualenv",
    ".ipynb_checkpoints": "Jupyter checkpoints",
    # Terraform / infra
    ".terraform": "Terraform providers/modules — terraform init",
    # Rust
    "target": "Rust/Cargo build output",
    # Java / JVM / Gradle / Maven
    ".gradle": "Gradle cache",
    # PHP / Ruby
    "vendor": "Composer/Go vendored deps",
    # Build output (generic)
    "build": "build output",
    "dist": "distribution/build output",
    "out": "build output",
    ".cache": "generic tool cache",
    # Native / C / C++
    ".ccache": "compiler cache",
    "DerivedData": "Xcode derived data",
    # misc
    ".gradle-cache": "Gradle cache",
}

# Some names (build/dist/out/vendor) are ambiguous; mark them so the UI can
# flag them as "verify before deleting".
AMBIGUOUS = {"build", "dist", "out", "vendor", "venv"}


@dataclass
class Finding:
    """A detected residual artifact."""

    name: str
    path: str
    size: int
    reason: str
    ambiguous: bool
    checked: bool = False  # UI toggle state

    @property
    def kind(self) -> str:
        return self.name


def detect(root: Node) -> List[Finding]:
    """Walk ``root`` and return residual-artifact findings, largest-first.

    Does not descend into a directory once it has been matched.
    """
    findings: List[Finding] = []

    def walk(node: Node) -> None:
        if not node.is_dir:
            return
        name = node.name
        if name in KNOWN_ARTIFACTS:
            findings.append(
                Finding(
                    name=name,
                    path=node.path,
                    size=node.size,
                    reason=KNOWN_ARTIFACTS[name],
                    ambiguous=name in AMBIGUOUS,
                )
            )
            return  # don't descend into a matched artifact
        for child in node.children:
            if child.is_dir:
                walk(child)

    walk(root)
    findings.sort(key=lambda f: f.size, reverse=True)
    return findings


def total_size(findings: List[Finding], checked_only: bool = False) -> int:
    return sum(f.size for f in findings if (f.checked or not checked_only))


def delete_findings(findings: List[Finding], root_path: str) -> dict:
    """Delete every *checked* finding. Returns a report dict.

    Safety guards (all must hold or the item is skipped):
      * the path is a directory that still exists,
      * its basename is in :data:`KNOWN_ARTIFACTS`,
      * it resolves to somewhere *inside* ``root_path`` (no escaping via
        symlinks/``..``), and is not the root itself.

    Returns ``{"deleted": [...], "errors": [(path, msg)], "freed": bytes}``.
    """
    import os
    import shutil

    root_real = os.path.realpath(root_path)
    report = {"deleted": [], "errors": [], "freed": 0}

    for f in findings:
        if not f.checked:
            continue
        p = f.path
        try:
            real = os.path.realpath(p)
            base = os.path.basename(p.rstrip("/"))

            # --- guards ---
            if base not in KNOWN_ARTIFACTS:
                report["errors"].append((p, "name no longer recognized as artifact"))
                continue
            if real == root_real:
                report["errors"].append((p, "refusing to delete the scan root"))
                continue
            if not (real == root_real or real.startswith(root_real + os.sep)):
                report["errors"].append((p, "path escapes the scanned root"))
                continue
            if not os.path.isdir(real):
                report["errors"].append((p, "not a directory / already gone"))
                continue

            shutil.rmtree(real)
            report["deleted"].append(p)
            report["freed"] += f.size
        except Exception as exc:  # noqa: BLE001
            report["errors"].append((p, str(exc)))

    return report


def delete_paths(paths, root_path: str) -> dict:
    """Delete the given artifact ``paths`` (web API helper).

    Builds :class:`Finding` objects for the requested paths by re-detecting
    sizes from disk is unnecessary — we trust the caller's path list but still
    apply every guard in :func:`delete_findings`. Only paths whose basename is a
    known artifact and that live inside ``root_path`` are removed.
    """
    import os

    findings = []
    wanted = set(paths)
    for p in wanted:
        base = os.path.basename(p.rstrip("/"))
        size = 0
        try:
            # best-effort size for the freed report (allocated blocks)
            size = _dir_size(p)
        except OSError:
            size = 0
        findings.append(
            Finding(
                name=base,
                path=p,
                size=size,
                reason=KNOWN_ARTIFACTS.get(base, ""),
                ambiguous=base in AMBIGUOUS,
                checked=True,
            )
        )
    return delete_findings(findings, root_path)


def _dir_size(path: str) -> int:
    """Allocated size of a directory tree (used only for the freed report)."""
    import os

    total = 0
    for dirpath, dirnames, filenames in os.walk(path):
        for name in filenames:
            try:
                st = os.lstat(os.path.join(dirpath, name))
                blocks = getattr(st, "st_blocks", None)
                total += blocks * 512 if blocks is not None else st.st_size
            except OSError:
                continue
    return total
